train_loader = DataLoader(TensorDataset(X_train_t, y_train_t), batch_size=64, shuffle=True)

# --- Define Architectures (Constrained to ~2500 parameters) ---
input_dim = X_train.shape[1]
output_dim = len(unique_labels)

# WIDE: 1 Hidden Layer (130 units)
# Params: (11*130) + 130 + (130*7) + 7 = 2477
class WideNet(nn.Module):
    def __init__(self):
        super(WideNet, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 130),
            nn.ReLU(),
            nn.Linear(130, output_dim)
        )
    def forward(self, x): return self.net(x)

# DEEP: 3 Hidden Layers (30 units each)
# Params: (11*30)+30 + (30*30)+30 + (30*30)+30 + (30*7)+7 = ~2400
class DeepNet(nn.Module):
    def __init__(self):
        super(DeepNet, self).__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 30),
            nn.ReLU(),
            nn.Linear(30, 30),
            nn.ReLU(),
            nn.Linear(30, 30),
            nn.ReLU(),
            nn.Linear(30, output_dim)
        )
    def forward(self, x): return self.net(x)

# --- Training Function (Strict SGD) ---
def train_and_evaluate(model, name, epochs=150):
    # REQUIREMENT: SGD only, no momentum, no Adam
    optimizer = optim.SGD(model.parameters(), lr=0.1, momentum=0.0)
    criterion = nn.CrossEntropyLoss()

    metrics = {'loss': [], 'val_f1': [], 'val_acc': []}

    for epoch in range(epochs):
        model.train()
        batch_loss = 0
        for bx, by in train_loader:
            optimizer.zero_grad()
            output = model(bx)
            loss = criterion(output, by)
            loss.backward()
            optimizer.step()
            batch_loss += loss.item()

        # Validation stats
        model.eval()
        with torch.no_grad():
            val_out = model(X_test_t)
            _, preds = torch.max(val_out, 1)
            f1 = f1_score(y_test_t, preds, average='macro')
            acc = accuracy_score(y_test_t, preds)

        metrics['loss'].append(batch_loss / len(train_loader))
        metrics['val_f1'].append(f1)
        metrics['val_acc'].append(acc)

    return metrics

