    train_time = end_train - start_train

    # B. Timing Prediction
    start_pred = time.time()
    y_pred = model.predict(X_test)
    end_pred = time.time()
    pred_time = end_pred - start_pred

    # C. Metrics
    # Convert PyTorch tensors back to numpy if necessary
    if name == "Neural Net (Wide)":
        # Handle potential tensor output from the wrapper
        if hasattr(y_pred, 'numpy'): y_pred = y_pred.numpy()

    score = f1_score(y_test, y_pred, average='macro')

    # Store results
    results.append({
        "Model": name,
        "Train Time": train_time,
        "Predict Time": pred_time,
        "Macro F1": score
    })

    conf_matrices[name] = confusion_matrix(y_test, y_pred)

    print(f"{name:<20} | {train_time:<15.4f} | {pred_time:<15.4f} | {score:<10.4f}")

