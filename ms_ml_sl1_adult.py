def train_model(model, name, epochs=50, learning_rate=0.01):
    # Requirement: SGD, No Momentum [4]
    optimizer = optim.SGD(model.parameters(), lr=learning_rate, momentum=0.0)
    criterion = nn.CrossEntropyLoss()

    train_losses = []
    val_accuracies = []

    print(f"Training {name} with SGD (lr={learning_rate})...")

    for epoch in range(epochs):
        model.train()
        batch_loss = 0
        for bx, by in train_loader:
            optimizer.zero_grad()
            outputs = model(bx)
            loss = criterion(outputs, by)
            loss.backward()
            optimizer.step()
            batch_loss += loss.item()

        # Record average loss
        train_losses.append(batch_loss / len(train_loader))

        # Validation Check (Fast forward pass)
        model.eval()
        with torch.no_grad():
            val_out = model(test_tensor_x)
            _, predicted = torch.max(val_out, 1)
            acc = (predicted == test_tensor_y).sum().item() / len(test_tensor_y)
            val_accuracies.append(acc)

    return train_losses, val_accuracies

