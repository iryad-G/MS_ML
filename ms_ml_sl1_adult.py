# --- 2. Define Model Architecture ---
# Must match Sklearn capacity roughly (64 -> 32)
class BinaryMLP(nn.Module):
    def __init__(self, input_dim):
        super(BinaryMLP, self).__init__()
        self.layers = nn.Sequential(
            nn.Linear(input_dim, 64),
            nn.ReLU(),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 2) # Output layer (2 classes)
        )

    def forward(self, x):
        return self.layers(x)

# --- 3. Training Loop (SGD Only) ---
model = BinaryMLP(input_dim=X_train_trans.shape[1]) # Correct input dimension
optimizer = optim.SGD(model.parameters(), lr=0.1, momentum=0.0)
criterion = nn.CrossEntropyLoss()

loss_history = []
epochs = 50

print(f"\nTraining PyTorch MLP (SGD) for {epochs} epochs...")

for epoch in range(epochs):
    epoch_loss = 0
    for batch_X, batch_y in train_loader:
        optimizer.zero_grad()
        outputs = model(batch_X)
        loss = criterion(outputs, batch_y)
        loss.backward()
        optimizer.step()
        epoch_loss += loss.item()

    # Store average loss per epoch
    loss_history.append(epoch_loss / len(train_loader))

    if (epoch+1) % 10 == 0:
        print(f"Epoch [{epoch+1}/{epochs}], Loss: {loss_history[-1]:.4f}")

# --- 4. Plot PyTorch Curve ---
plt.figure(figsize=(8, 5))
